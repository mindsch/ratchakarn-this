// Compile the prompt pack (prompts/) into:
//   public/prompts/*.md   copy-paste prompts for any chat AI
//   src/generated/prompts.ts   strings the web app uses as system prompts
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, "prompts", p), "utf8").trim();
const doctypes = readdirSync(join(root, "prompts", "doctypes"))
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => read(join("doctypes", f)))
  .join("\n\n");

const core = read("core.md");
const template = read("output-template.md");
const disclaimer = read("disclaimer.md");
const modes = {
  convert: read("modes/convert.md"),
  draft: read("modes/draft.md"),
  interview: read("modes/interview.md"),
  format: read("modes/format.md"),
  court: read("modes/court.md"),
  check: read("modes/check.md"),
  prefill: read("modes/prefill.md"),
  draftBody: read("modes/draft-body.md"),
};

const join2 = (...parts) => parts.filter(Boolean).join("\n\n---\n\n") + "\n";

// What each mode needs, to keep prompts small for small models.
const systemPrompts = {
  convert: join2(core, modes.convert, disclaimer),
  draft: join2(core, modes.draft, doctypes, template, disclaimer),
  format: join2(core, modes.format, template, disclaimer),
  court: join2(core, modes.court, template, disclaimer),
  // In-app one-shot AI actions (contracts: src/lib/ai.ts)
  check: join2(core, modes.check),
  prefill: join2(modes.prefill),
  draftBody: join2(core, modes.draftBody, doctypes),
};

const modeMenu = `# วิธีเลือกโหมด
ผู้ใช้เลือกโหมดด้วยการพิมพ์ชื่อโหมดหรืออธิบายสิ่งที่ต้องการ:
- "แปลงภาษา" (ระบุระดับ 0-4 ได้) → ทำตามโหมดแปลงภาษา
- "ร่างเอกสาร" → ทำตามโหมดร่างเอกสาร
- "ช่วยถาม" → ทำตามโหมดช่วยถาม (สัมภาษณ์ทีละข้อ)
- "จัดรูปแบบ" หรือ "ตรวจ" แล้ววางข้อความ → ทำตามโหมดจัดรูปแบบ
- "ศาลแรงงาน" → ทำตามโหมดศาล (ศาลแรงงานเท่านั้น)
ถ้าผู้ใช้ยังไม่เลือก ให้ทักทายสั้นๆ แล้วถามว่าต้องการโหมดไหน`;

const all = join2(
  "# แปลเป็นราชการ (Ratchakarn-this) — พรอมต์ฉบับรวม (วางเป็นคำสั่งระบบ/คำสั่งแรกใน Claude, ChatGPT, Gemini, หรือ AI ใดก็ได้)",
  core,
  modeMenu,
  modes.convert,
  modes.draft,
  modes.interview,
  modes.format,
  modes.court,
  doctypes,
  template,
  disclaimer,
);

const compact = join2(
  "# แปลเป็นราชการ (Ratchakarn-this) — แปลงภาษาเป็นภาษาราชการ (เหมาะกับโมเดลเล็กหรือช่องคำสั่งที่จำกัดความยาว)",
  core,
  modes.convert,
  disclaimer,
);
const interview = join2(core, modes.interview, doctypes, template, disclaimer);

// One entry per outcome on the พรอมต์ page. text is the real file content; sizes are computed in the UI.
const copyDefs = {
  convert: { label: "แปลงภาษา", desc: "เปลี่ยนข้อความทั่วไปเป็นภาษาราชการ เลือกระดับได้ 0–4 โดยไม่เปลี่ยนข้อเท็จจริง", pasteInto: "ChatGPT · Claude · Gemini · โมเดลไทยหรือโมเดลเล็ก", file: "ratchakarn-convert.md", text: compact },
  draft: { label: "ช่วยร่าง", desc: "ให้ AI ร่างหนังสือราชการตามชนิดและวัตถุประสงค์ ช่องที่ไม่มีข้อมูลจะเว้นเป็น [ระบุ...]", pasteInto: "ChatGPT Project · Claude Project · Gemini Gem", file: "ratchakarn-draft.md", text: systemPrompts.draft },
  interview: { label: "ช่วยถาม", desc: "AI ถามข้อเท็จจริงที่ขาดทีละข้อก่อนร่าง คุณตอบ แล้วจึงได้ร่างที่ไม่เดา", pasteInto: "ใช้ใน AI ภายนอกเท่านั้น ในเว็บนี้ไม่มีแชตถามตอบ", file: "ratchakarn-interview.md", text: interview },
  checkFormat: { label: "ตรวจ & จัดรูปแบบ", desc: "AI ตรวจคำผิด คำที่ควรเปลี่ยน และรูปแบบ แล้วจัดลงแม่แบบโดยไม่เปลี่ยนถ้อยคำของคุณ", pasteInto: "วางหลังจากคุณมีร่างแล้ว ผลที่ได้ใช้ในจัดรูปแบบต่อได้", file: "ratchakarn-check-format.md", text: systemPrompts.format },
  court: { label: "ศาลแรงงาน", desc: "ร่างคำฟ้อง บัญชีพยาน และคำร้องคดีแรงงานเบื้องต้น ต้องให้ผู้รู้กฎหมายตรวจก่อนยื่น", pasteInto: "ChatGPT Project · Claude Project · Gemini Gem", file: "ratchakarn-court-labour.md", text: systemPrompts.court },
  all: { label: "ฉบับรวม", desc: "พรอมต์เดียวรวมทุกโหมด (แปลงภาษา ร่าง ถาม จัดรูปแบบ ศาลแรงงาน) ไฟล์ใหญ่ ใช้เมื่อ AI รับข้อความยาวได้ และอยากสลับงานในแชตเดียวด้วยการพิมพ์ชื่อโหมด", pasteInto: "คำสั่งระบบ หรือข้อความแรกของแชต", file: "ratchakarn-all.md", text: all },
};

mkdirSync(join(root, "public", "prompts"), { recursive: true });
mkdirSync(join(root, "src", "generated"), { recursive: true });
for (const d of Object.values(copyDefs)) writeFileSync(join(root, "public", "prompts", d.file), d.text);

const ts = `// GENERATED by scripts/build-prompts.mjs — do not edit.
export const SYSTEM_PROMPTS = ${JSON.stringify(systemPrompts, null, 2)} as const;
export interface CopyPrompt { label: string; desc: string; pasteInto: string; file: string; text: string }
export const COPY_PROMPTS = ${JSON.stringify(copyDefs, null, 2)} as const satisfies Record<string, CopyPrompt>;
`;
writeFileSync(join(root, "src", "generated", "prompts.ts"), ts);
console.log("prompts built:");
for (const d of Object.values(copyDefs)) console.log(" ", d.file, d.text.length, "chars");
